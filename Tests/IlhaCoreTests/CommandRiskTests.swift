@Test(arguments: [
  "git push",
  "git push --force origin main",
  "git -C /repo push origin HEAD",
  "npm publish",
  "pnpm publish --access public",
  "yarn publish",
  "vercel --prod",
  "fly deploy",
  "kubectl apply -f deploy.yaml",
  "kubectl delete pod web-1",
  "terraform apply -auto-approve",
  "terraform destroy",
  "gh pr merge 12 --squash",
  "gh release create v1.0",
  "rm -rf /tmp/foo",
  "rm -rf ~/Documents",
  "curl -X POST https://api.x/y",
  "curl -XDELETE https://api.x/y/1",
  "curl --request PUT https://api.x/y",
  "curl -d '{\"a\":1}' https://api.x/y",
  "curl --data-binary @f https://api.x/y",
  "wget --post-data=a=1 https://x",
  "ssh deploy@host ls",
  "scp build.tar host:/srv",
  "rsync -av dist/ user@host:/srv/www",
  "docker push me/app:latest",
  // Tokenização: encadeado, pipe, sudo, prefixo de ambiente, shell -c.
  "git status && git push",
  "npm test; git push origin main",
  "FOO=1 git push",
  "sudo git push",
  "sudo -u deploy kubectl apply -f x.yaml",
  "env GIT_SSH=x git push",
  "bash -c 'git push origin main'",
  "echo ok | xargs rm -rf",
  "/usr/bin/ssh host",
  "rm -rf node_modules ../outro",
  // Continuação de linha.
  "git \\\n push",
  "fly \\\n deploy",
  "gh \\\n pr merge 1",
  // Opções globais antes do subcomando.
  "gh -R o/r pr merge 1",
  "gh pr --repo x merge",
  "gh release --repo x create v1",
  "fly -a app deploy",
  "npm -w a -w b publish",
  "yarn workspace foo publish",
  "vercel env rm X",
  "vercel projects rm x",
  "vercel domains add x.com",
  // Formas que já passavam.
  "git push origin main --force-with-lease",
  "cd x && npm publish",
  "sudo rm -rf /",
  "rm -fr x",
  "rm -r -f x",
  "kubectl --context x delete pod y",
])
func riskyCommands(_ c: String) {
  #expect(CommandRisk.touchesOutsideMac(c), "deveria ser arriscado: \(c)")
}

